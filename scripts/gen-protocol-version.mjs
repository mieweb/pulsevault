#!/usr/bin/env node
// Writes src/lib/protocol-version.gen.ts from package.json `pulseProtocol` — the one place the
// protocol version is written down (PROTOCOL.md §7). Runs before `tsc` in `npm run build`.
//
// The version is baked in at build time rather than read from package.json at runtime:
// `createRequire(import.meta.url)` is valid ESM for Node, but bundlers that compile npm
// packages into their own module wrapper reject it — Meteor's wrapper already declares
// `require` ("Identifier 'require' has already been declared") and can't compile `import.meta`.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
const { version, min, max } = pkg.pulseProtocol ?? {};
// Fail the build, not the first request: protocol.ts checks the numbers agree at load time.
if (!/^\d+\.\d+$/.test(String(version)) || !Number.isInteger(min) || !Number.isInteger(max)) {
  throw new Error(`package.json pulseProtocol is missing or malformed: ${JSON.stringify(pkg.pulseProtocol)}`);
}

const out = `// GENERATED by scripts/gen-protocol-version.mjs from package.json \`pulseProtocol\`.
// Do not edit: change package.json, then run \`npm run build\`.

export const PULSE_PROTOCOL: { version: string; min: number; max: number } = {
  version: '${String(version).replace(/['\\]/g, "\\$&")}',
  min: ${JSON.stringify(min)},
  max: ${JSON.stringify(max)},
};
`;

const target = path.join(root, "src", "lib", "protocol-version.gen.ts");
const current = await fs.readFile(target, "utf8").catch(() => null);
if (current !== out) await fs.writeFile(target, out);
