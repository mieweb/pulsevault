#!/usr/bin/env node
// Writes the Pulse icon files in assets/ from the logo itself (assets/pulse-logo.svg): the same
// drawing, placed in a square. `--check` writes nothing and fails if a committed file is stale
// (test/assets.test.mjs runs it).
//
// Why an icon beside the logo: the logo is 87 × 100, and a button's icon is square. Sized by its
// height, a logo and a square icon beside it don't line up, and a host has to know the ratio to
// set a width. The icon is the logo centred in a square 24 × 24 box at its full height, so at any
// size it is the logo at that height, and one design serves every size.
//
// Three colourings, three files:
//   pulse-icon.svg         the logo's red gradient
//   pulse-icon-mono.svg    `currentColor`, to colour with CSS or use as a mask
//   pulse-icon-white.svg   white, for an <img> on a filled button
//
// The shape is read from the logo file, never restated here: change the logo and run
// `npm run icons`, and the icon follows.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const assets = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "assets");
const SIZE = 24;

const logo = await fs.readFile(path.join(assets, "pulse-logo.svg"), "utf8");
const viewBox = /viewBox="([-\d. ]+)"/.exec(logo)?.[1].split(/\s+/).map(Number);
const shape = /<mask[^>]*>([\s\S]*?)<\/mask>/.exec(logo)?.[1].trim();
const stops = /<linearGradient[^>]*>([\s\S]*?)<\/linearGradient>/.exec(logo)?.[1].trim();
if (viewBox?.length !== 4 || viewBox.some(Number.isNaN) || !shape || !stops) {
  throw new Error("assets/pulse-logo.svg isn't the drawing this script reads: a viewBox, one mask, one gradient");
}

// The logo's box, scaled to the square's full height and centred across it.
const [minX, minY, width, height] = viewBox;
const scale = SIZE / height;
const round = (n) => Number(n.toFixed(4));
const place = `translate(${round((SIZE - width * scale) / 2)} 0) scale(${round(scale)}) translate(${-minX} ${-minY})`;

/** What fills the shape, per colouring: `defs` it needs, given the file's own id prefix. */
const PAINTS = {
  "": (id) => ({
    fill: `url(#${id}-red)`,
    defs:
      `\n    <linearGradient id="${id}-red" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="${SIZE}">` +
      `\n      ${stops.replace(/\s*\n\s*/g, "\n      ")}\n    </linearGradient>`,
  }),
  "-mono": () => ({ fill: "currentColor", defs: "" }),
  "-white": () => ({ fill: "#fff", defs: "" }),
};

/** One icon file. Its ids carry its own name, so several can be inlined on one page. */
function icon(name, paint) {
  const { fill, defs } = paint(name);
  return `<!-- GENERATED by scripts/gen-pulse-icons.mjs from pulse-logo.svg. Do not edit: run \`npm run icons\`. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" role="img" aria-label="Pulse">
  <title>Pulse</title>
  <defs>${defs}
    <mask id="${name}-shape" maskUnits="userSpaceOnUse" x="0" y="0" width="${SIZE}" height="${SIZE}">
      <g transform="${place}">
        ${shape.replace(/\s*\n\s*/g, "\n        ")}
      </g>
    </mask>
  </defs>
  <rect width="${SIZE}" height="${SIZE}" fill="${fill}" mask="url(#${name}-shape)"/>
</svg>
`;
}

const files = Object.entries(PAINTS).map(([colouring, paint]) => {
  const name = `pulse-icon${colouring}`;
  return { file: `${name}.svg`, svg: icon(name, paint) };
});

const check = process.argv.includes("--check");
let stale = 0;
for (const { file, svg } of files) {
  const target = path.join(assets, file);
  const current = await fs.readFile(target, "utf8").catch(() => null);
  if (current === svg) continue;
  if (check) {
    console.error(`✗ assets/${file} is stale — run \`npm run icons\` and commit it`);
    stale++;
  } else {
    await fs.writeFile(target, svg);
    console.log(`wrote assets/${file}`);
  }
}
if (stale) process.exit(1);
if (check) console.log(`✓ ${files.length} Pulse icon files are up to date`);
